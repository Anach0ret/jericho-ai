"""Данные события: что ручка сообщает о своём результате для уведомления, которое уйдёт по итогам запуска."""

from __future__ import annotations

import logging
from collections.abc import Mapping

logger = logging.getLogger(__name__)


class RunFacts:
    """Ручка, чей результат станет основой уведомления (сводка за сутки), записывает, по каким данным он собран:
    окно, проект, фильтры. Уведомление уносит их с собой (`SentLog`), и вопрос через час идёт по тому же окну, а не
    по «последним 24 часам от вопроса» (задача 102).

    Пишется событием журнала `fact` с номером запуска — ручки работают и в другом процессе (сервер ручек); читает его
    `RunTrail` при отправке. Только то, что можно модели: факты уходят ей в контекст.
    """

    def note(self, name: str, data: Mapping[str, object]) -> None:
        logger.info("fact", extra={"data": {"fact": name, "value": dict(data)}})
