"""Чужой текст: что модель уже прочитала в этой фразе из источников, которым нельзя верить как пользователю."""

from __future__ import annotations

import logging

logger = logging.getLogger(__name__)


class ForeignText:
    """Помнит, откуда в эту фразу попал чужой текст: страница сайта, список роликов, письмо.

    Чужой текст может содержать указания — «открой такой-то адрес», «запомни это». Модель обязана их не слушать,
    но держит это промпт, а не код. Поэтому ручка, которая отдала модели чужой текст, сообщает об этом сюда,
    а ручки, чьим действием пользуется внедрённая команда, спрашивают: было ли такое в этой фразе и откуда.
    Что из этого следует, решает каждая ручка: служба только помнит.

    Живёт одну фразу, как и процесс сервера ручек.
    """

    def __init__(self) -> None:
        self._sources: set[str] = set()

    def read_from(self, source: str) -> None:
        """Ручка отдала модели текст из этого источника: адрес сайта без «www.» или имя источника.

        Первое чтение источника пишется в журнал (`foreign`): по нему следующие фразы узнают, что в разговоре,
        который им показывают, был чужой текст — учёт не теряется между процессами.
        """
        source = source.casefold()
        if source not in self._sources:
            logger.info("foreign", extra={"data": {"source": source}})
        self._sources.add(source)

    def restore(self, source: str) -> None:
        """Источник, который уже читали раньше (его ответ снова в разговоре): учёт — да, запись в журнал — нет.

        В журнал его записала та фраза. Иначе каждая сборка ассистента писала бы его заново — а окно на панели
        собирает его раз в 2 секунды (журнал 23.10.2026: `foreign` каждые две секунды).
        """
        self._sources.add(source.casefold())

    @property
    def sources(self) -> frozenset[str]:
        return frozenset(self._sources)
