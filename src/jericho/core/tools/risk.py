"""Класс риска ручки: что она делает с миром, от безобидного к необратимому."""

from __future__ import annotations

from enum import StrEnum


class Risk(StrEnum):
    """Объявляется в классе каждой ручки. Не объявлен — ручка считается самой опасной, а `jericho check` это находит.

    Класс говорит о ручке в целом, по самому тяжёлому, что она умеет. Запреты внутри класса — какое окно своё,
    какое слово нельзя нажимать, какой сайт закрыт — остаются делом самой ручки и её навыка.
    """

    READ = "read"            # только читает: ничего не меняется
    NAVIGATE = "navigate"    # открывает и переключает: вернуть как было — одно действие
    CHANGE = "change"        # меняет состояние, но поправимо: громкость, раскладка окон, заметка
    EFFECT = "effect"        # последствие не отменить или оно уходит наружу: закрыть, нажать, отправить

    @property
    def rank(self) -> int:
        """Порядок от безобидного к необратимому: так сравнивают ручку с пределом пользователя."""
        return list(Risk).index(self)


class Approval(StrEnum):
    """Кто спрашивает «да» перед ручкой `EFFECT`. Ручкам других классов не нужно.

    `ASK` — каркас, перед каждым вызовом: ручка ничего для этого не делает. `TOOL` — сама ручка, через
    `ConfirmationGate`, когда это нужно (закрыть одно окно — без вопроса, пять — с вопросом). Выбор `TOOL`
    объявляется в классе явно: проверка E008 не даёт ему достаться случайно.
    """

    ASK = "ask"
    TOOL = "tool"
